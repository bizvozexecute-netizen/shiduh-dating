/*
 * Применить решение пользователя после сохранения анкеты.
 *
 * $given — отметил ли человек галочку в этой отправке формы.
 * Возвращает array('consent' => 0|1, 'erased' => bool).
 *
 * Правило: согласие есть → штампуем дату и версию; согласия нет → снимаем
 * флаг и СТИРАЕМ защищённые поля (в т.ч. заполненные ранее).
 */
function consent_apply($db, $message_id, $given) {
    $id = (int)$message_id;
    if ($id <= 0) {
        return array('consent' => 0, 'erased' => false);
    }
    $given = $given ? 1 : 0;

    if ($given) {
        $db->query(
            "UPDATE `Message204` SET `Consent_sensitive`=1, "
            . "`Consent_sensitive_at`=NOW(), "
            . "`Consent_sensitive_version`='" . $db->prepare(consent_version()) . "' "
            . "WHERE `Message_ID`=$id"
        );
        return array('consent' => 1, 'erased' => false);
    }

    // Нет согласия — стираем защищённые поля. Дату и версию прошлого
    // согласия тоже снимаем: оно отозвано, ссылаться на него больше нельзя.
    $sets = array("`Consent_sensitive`=0", "`Consent_sensitive_at`=NULL",
                  "`Consent_sensitive_version`=NULL");
    foreach (consent_guarded_fields() as $f) {
        $sets[] = "`" . $f . "`=''";
    }
    $db->query("UPDATE `Message204` SET " . implode(', ', $sets) . " WHERE `Message_ID`=$id");
    return array('consent' => 0, 'erased' => true);
}
