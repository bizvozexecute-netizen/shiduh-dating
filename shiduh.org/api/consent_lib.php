/*
 * Согласие на обработку сведений о здоровье (ROADMAP X-5, 152-ФЗ).
 *
 * Здесь три вещи, которые должны жить в ОДНОМ месте:
 *   1) текст согласия и его версия — что именно человек подтверждает;
 *   2) правило «нет согласия → нет данных о здоровье» (серверная гарантия);
 *   3) фиксация «когда и на какую редакцию» — согласие должно быть доказуемым.
 *
 * Почему поле здоровья стирается, а не просто «не показывается»: закон
 * запрещает ОБРАБОТКУ спецкатегории без согласия, а хранение — это уже
 * обработка. Поэтому отзыв согласия удаляет данные, а не прячет их.
 *
 * ВАЖНО: текст ниже — рабочая формулировка, составленная разработчиком.
 * Перед выкаткой на прод её должен вычитать юрист: состав данных, срок,
 * порядок отзыва и адрес оператора зависят от реквизитов организации.
 * Версию при правке текста ОБЯЗАТЕЛЬНО поднимать (consent-v2 и т.д.):
 * согласие, данное на старую редакцию, не распространяется на новую.
 */

/* Версия текста. Меняется ВМЕСТЕ с текстом — иначе теряется доказуемость. */
function consent_version() {
    return 'consent-v1';
}

/* Поля, которые разрешено хранить только при действующем согласии. */
function consent_guarded_fields() {
    // Health_status — единственное поле спецкатегории, которое человек
    // заполняет сам в форме. Остальные чувствительные поля (доход,
    // заболевания, медикаменты) в форму не выведены; если их когда-нибудь
    // выведут — добавить сюда, и правило заработает автоматически.
    return array('Health_status');
}

/*
