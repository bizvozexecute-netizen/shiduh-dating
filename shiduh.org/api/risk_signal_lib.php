<?php
/*
 * «Сигнал внимания» для шадхана (ROADMAP X-3).
 *
 * Шадханы просили «улавливать адекватность из переписки». В лоб это
 * псевдопсихиатрия и юридический риск, поэтому рамка узкая и жёсткая:
 *
 *   - сигнал НЕ диагноз, НЕ оценка личности и НЕ ярлык; это повод живому
 *     человеку присмотреться. Решение всегда за шадханом;
 *   - категории поведенческие и наблюдаемые (что видно в тексте), а не
 *     клинические сущности;
 *   - в заметку НЕ попадает НИЧЕГО из переписки: сохраняется только
 *     категория, формулировку пишет сервер. Свободный текст модели
 *     отбрасывается — отличить пересказ от цитаты в нём невозможно
 *     (подробнее у risk_note_add);
 *   - хранится как заметка модерации (moderation_notes), отдельно от анкеты,
 *     и не влияет ни на подбор, ни на резюме;
 *   - кандидату это раскрыто в интерфейсе консультанта.
 *
 * Отдельного платного вызова модели нет: сигнал поднимает инструмент
 * report_safety_concern у самого консультанта (ai_tools.php) — модель и так
 * прочитала сообщение.
 */

/* Категории. Ключ → человекочитаемое название для шадхана. */
function risk_kinds() {
    return array(
        'aggression'  => 'Резкость или угрозы в переписке',
        'incoherence' => 'Бессвязность изложения',
        'distress'    => 'Признаки тяжёлого состояния',
    );
}

/* Что делать шадхану — подсказка под каждой категорией. */
function risk_kind_hint($kind) {
    $hints = array(
        'aggression'  => 'Стоит поговорить лично и составить собственное мнение.',
        'incoherence' => 'Возможно, человеку трудно писать текстом — попробуйте созвон.',
        // Здесь ответственность выше: это не повод «отбраковать» человека,
        // а повод по-человечески отнестись и подсказать, куда обратиться.
        'distress'    => 'Отнеситесь бережно. Если речь о безопасности человека, '
                       . 'предложите обратиться к раввину общины или к специалисту; '
                       . 'экстренная психологическая помощь в России — 8 800 2000-122.',
    );
    return isset($hints[$kind]) ? $hints[$kind] : '';
}

/* Оговорка, без которой сигнал показывать нельзя. */
function risk_disclaimer() {
    return 'Это не диагноз и не оценка личности, а лишь повод обратить внимание. '
         . 'Сигнал поставил алгоритм по тексту переписки, он может ошибаться. '
         . 'Решение всегда за вами.';
}

/*
 * Добавить сигнал. Возвращает true, если заметка создана.
 *
 * СВОБОДНЫЙ ТЕКСТ МОДЕЛИ НЕ СОХРАНЯЕТСЯ. Это не перестраховка: надёжно
 * отличить пересказ от цитаты в чужом тексте нельзя — модель может привести
 * фразу собеседника без кавычек, и никакой фильтр её не поймает. Значит,
 * обещание «в заметку не попадают цитаты из переписки» было бы ложным.
 * Поэтому в заметку идёт только КАТЕГОРИЯ, а формулировку пишет сервер:
 * она предсказуема и одинакова для всех.
 *
 * Что теряется: нюанс наблюдения. Что сохраняется: личная переписка
 * кандидата не пересказывается третьему лицу. Второе важнее.
 *
 * Дедупликация: одна заметка на пользователя и категорию в сутки — иначе
 * один разговор на повышенных тонах превращается в список из двадцати
 * одинаковых строк, и шадхан перестаёт их читать.
 */
function risk_note_add($db, $user_id, $kind, $model_note = '') {
    $user_id = (int)$user_id;
    $kinds = risk_kinds();
    if ($user_id <= 0 || !isset($kinds[$kind])) {
        return false;
    }

    $dupe = (int)$db->get_var(
        "SELECT COUNT(*) FROM `moderation_notes` WHERE `user_id`=$user_id "
        . "AND `kind`='" . $db->prepare($kind) . "' "
        . "AND `created_at` > DATE_SUB(NOW(), INTERVAL 1 DAY)"
    );
    if ($dupe > 0) {
        return false;
    }

    // $model_note намеренно игнорируется — см. комментарий выше.
    $db->query(
        "INSERT INTO `moderation_notes` SET `user_id`=$user_id, "
        . "`kind`='" . $db->prepare($kind) . "', "
        . "`note`='" . $db->prepare($kinds[$kind]) . "', "
        . "`source`='ai', `created_at`=NOW()"
    );
    return !$db->is_error;
}


/* Открытые сигналы по пользователю (для карточки шадхана). */
function risk_notes_open($db, $user_id) {
    $user_id = (int)$user_id;
    if ($user_id <= 0) {
        return array();
    }
    $db->query(
        "SELECT `id`, `kind`, `note`, `created_at` FROM `moderation_notes` "
        . "WHERE `user_id`=$user_id AND `resolved_at` IS NULL "
        . "ORDER BY `created_at` DESC LIMIT 20",
        ARRAY_A
    );
    return (array)$db->last_result;
}

/* Шадхан отметил, что посмотрел. */
function risk_note_resolve($db, $note_id, $by_user) {
    $id = (int)$note_id;
    $by = (int)$by_user;
    if ($id <= 0 || $by <= 0) {
        return false;
    }
    $db->query(
        "UPDATE `moderation_notes` SET `resolved_at`=NOW(), `resolved_by`=$by "
        . "WHERE `id`=$id AND `resolved_at` IS NULL"
    );
    return !$db->is_error;
}
