<?php
/*
 * Анкета, в которую пишет консультант, — одна на весь модуль ИИ (запись,
 * подтверждение, вопросы о замене, подсказки, приветствие). Раньше каждое
 * место брало «самую старую анкету владельца» само, без учёта проверки, а
 * «Рекомендованные пары» — проверенную: у человека с двумя анкетами ИИ писал
 * в одну, а показывали ему другую, и запись выглядела пропавшей.
 *
 * Правило: проверенная (Checked=1) раньше непроверенной, при равенстве —
 * самая старая. Шадхан своей анкеты не имеет: его «анкеты» — анкеты его
 * кандидатов (AUDIT.md §1, п.2), и рассказ шадхана о себе не должен
 * попадать в анкету клиента. Для него — 0, как «анкеты нет».
 */
require_once dirname(__FILE__) . '/admin_lib.php';   // shiduh_user_type()

function ai_target_anketa($db, $user_id) {
    $user_id = (int)$user_id;
    if (!$user_id) {
        return 0;
    }
    if (shiduh_user_type($db, $user_id) === 2) {
        return 0;
    }
    return (int)$db->get_var(
        "SELECT `Message_ID` FROM `Message204` WHERE `User_ID`=$user_id "
        . "ORDER BY `Checked` DESC, `Message_ID` LIMIT 1"
    );
}
