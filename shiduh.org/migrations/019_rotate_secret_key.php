<?php
/*
 * Ротация SecretKey (ROADMAP B-3, находка AUDIT №4).
 *
 * НА ПРОДЕ SecretKey = 'd41d8cd98f00b204e9800998ecf8427e' — это md5(''),
 * общеизвестная константа. Токен NetCat считается как md5($user_id . $key)
 * (netcat/system/nc_token.class.php), поэтому со знанием ключа валидный
 * nc_token для ЛЮБОГО пользователя вычисляется в одну строку — CSRF-защита
 * движка не работает вовсе. Именно поэтому наши собственные эндпоинты
 * проверяют Origin (api/admin_lib.php: shiduh_check_origin), а не nc_token.
 *
 * Миграция ИДЕМПОТЕНТНА и осторожна: ключ меняется ТОЛЬКО если он слабый
 * (пустой, md5('') или короче 32 символов). Если администратор уже поставил
 * нормальный ключ — не трогаем.
 *
 * ЧТО ЛОМАЕТСЯ ПРИ РОТАЦИИ (радиус поражения):
 *   - формы, уже открытые в браузерах, отправятся со старым nc_token и
 *     получат отказ: человеку надо обновить страницу. Это единственное
 *     заметное следствие, и оно кратковременное;
 *   - сессии НЕ затрагиваются (другой механизм, таблица Session) —
 *     разлогинивания не будет;
 *   - пароли, письма и ссылки-приглашения НЕ затрагиваются.
 * Отсюда «окно»: выкатывать в час наименьшей активности; см.
 * deploy/DEPLOY.prod.md, раздел о ротации ключа.
 *
 * down: НЕ возвращает прежнее значение. Вернуть общеизвестный ключ значило бы
 * заново открыть дыру, а старый случайный ключ хранить негде (и незачем —
 * ротация ключа обратной операции не имеет). Откат безопасен: при пустом
 * ключе ядро сгенерирует новый само (nc_token::get).
 */
return array(
    'up' => function ($nc) {
        $db = $nc->db;
        $weak = array(
            '',
            'd41d8cd98f00b204e9800998ecf8427e',   // md5('')
        );

        $row = $db->get_row(
            "SELECT `Value` FROM `Settings` WHERE `Key`='SecretKey' AND `Module`='system'",
            ARRAY_A
        );
        $current = $row ? (string)$row['Value'] : '';

        $is_weak = in_array($current, $weak, true) || strlen($current) < 32;
        if (!$is_weak) {
            echo "SecretKey уже стойкий — не трогаем\n";
            return;
        }

        // 20 байт из криптостойкого источника; random_bytes есть в PHP 7
        $key = bin2hex(random_bytes(20));

        if ($row) {
            $db->query("UPDATE `Settings` SET `Value`='" . $db->prepare($key) . "' "
                . "WHERE `Key`='SecretKey' AND `Module`='system'");
        } else {
            $db->query("INSERT INTO `Settings` SET `Key`='SecretKey', "
                . "`Value`='" . $db->prepare($key) . "', `Module`='system', `Catalogue_ID`=0");
        }
        echo "SecretKey заменён на случайный (открытые формы потребуют обновления страницы)\n";
    },

    'down' => function ($nc) {
        // Осознанно ничего не делаем — см. шапку файла.
        echo "SecretKey не возвращается к прежнему значению (это было бы возвратом дыры)\n";
    },
);
