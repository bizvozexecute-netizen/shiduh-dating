<?php
/*
 * Заданные консультантом вопросы «поменять X на Y?» (этап «До идеала», B6).
 *
 * ТЗ Э1.3 требует не перезаписывать заполненное поле молча, а спросить и
 * поменять только после явного согласия. Согласие приходит следующей
 * репликой — значит между вопросом и ответом нужно где-то держать сам
 * вопрос. В переписке его держать нельзя: текст реплики пишет модель, и
 * «поменять на Ашдод» в её словах ничем не подтверждено — при подтверждении
 * значение могло бы разъехаться с тем, что человек видел.
 *
 * Поэтому вопрос — строка в таблице, а инструмент подтверждения не принимает
 * значения вовсе: он лишь называет поле, а что именно записать, сервер берёт
 * отсюда. Подменить значение в момент согласия нечем.
 *
 * Колонки:
 *   field           — колонка Message204 (то, что реально меняется);
 *   tool_key        — ключ инструмента (city, kashrut_level): им оперирует
 *                     модель, и по нему же приходит подтверждение;
 *   current_value   — снимок значения на момент вопроса, как оно хранится
 *                     (для справочников — ID). Если к моменту согласия живое
 *                     значение другое, человек успел поправить анкету сам —
 *                     старое согласие уже не о том, и вопрос сгорает;
 *   proposed_value  — что будет записано, тоже в хранимом виде;
 *   *_label         — то же по-человечески (имя из справочника): в промпт и
 *                     в подсказки должны идти слова, а не идентификаторы;
 *   thread          — диалог, в котором вопрос задан. «Да» в новом разговоре
 *                     не должно подтверждать вопрос из старого, а полагаться
 *                     на то, что клиент позовёт приветствие и тем очистит
 *                     хвосты, нельзя: номер диалога приходит от клиента;
 *   asked_message_id — id реплики человека, в ответ на которую задан вопрос.
 *                     Подтверждение засчитывается ровно одной следующей
 *                     репликой: раньше — модель договорилась сама с собой,
 *                     позже — человек уже ответил (в том числе «нет»), и
 *                     согласие на другой вопрос зачлось бы за согласие на
 *                     этот.
 *
 * UNIQUE(user_id, field): по полю висит ровно один вопрос — последний.
 * Передумала модель по ходу разговора — REPLACE заменит строку, и человек
 * подтвердит то, что видел последним.
 *
 * Обратимость: down удаляет таблицу. Ничего, кроме незаданных вопросов, в
 * ней не живёт — анкеты и переписка не затрагиваются.
 */

return array(
    'up' => function ($nc) {
        $nc->db->query("CREATE TABLE IF NOT EXISTS `ai_pending_overwrites` (
            `id` int(11) NOT NULL AUTO_INCREMENT,
            `user_id` int(11) NOT NULL,
            `field` varchar(64) NOT NULL,
            `tool_key` varchar(64) NOT NULL,
            `thread` int(11) NOT NULL DEFAULT 1,
            `current_value` text,
            `current_label` varchar(255) DEFAULT NULL,
            `proposed_value` text,
            `proposed_label` varchar(255) DEFAULT NULL,
            `asked_message_id` int(11) NOT NULL DEFAULT 0,
            `asked_at` datetime NOT NULL,
            PRIMARY KEY (`id`),
            UNIQUE KEY `user_field` (`user_id`,`field`)
        ) ENGINE=MyISAM DEFAULT CHARSET=utf8");
    },

    'down' => function ($nc) {
        $nc->db->query("DROP TABLE IF EXISTS `ai_pending_overwrites`");
    },
);
