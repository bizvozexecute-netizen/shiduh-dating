<?php
/*
 * Правка перевёрнутой формулировки сценария опроса (измерение «слова»).
 *
 * Стартовый текст был: «Супруг(а) вернулся с трудного дня. Что вам самому
 * важнее услышать в такой момент…» — читалось как «супруг устал, а поддержки
 * ждёте вы». Сценарий измеряет, важно ли САМОМУ человеку слышать поддержку,
 * поэтому с трудного дня должен возвращаться он.
 *
 * Меняем только если текст всё ещё стартовый: администратор мог уже
 * переписать его в admin-cases.php, и его правку затирать нельзя. По той же
 * причине down возвращает старый текст только поверх нового. Посевные данные
 * в 010 исправлены для новых установок; эта миграция — для уже развёрнутых.
 */

$OLD = 'Супруг(а) вернулся с трудного дня. Что вам самому важнее услышать в такой момент: слова поддержки и признания — или что-то другое?';
$NEW = 'Вы вернулись домой после трудного дня. Что вам важнее всего в такой момент: услышать слова поддержки и признания — или что-то другое?';

return array(
    'up' => function ($nc) use ($OLD, $NEW) {
        $db = $nc->db;
        $db->query(
            "UPDATE `assessment_cases` SET `scenario_text`='" . $db->prepare($NEW) . "' "
            . "WHERE `dimension_group`='love_language' AND `dimension`='words' "
            . "AND `scenario_text`='" . $db->prepare($OLD) . "'"
        );
    },

    'down' => function ($nc) use ($OLD, $NEW) {
        $db = $nc->db;
        $db->query(
            "UPDATE `assessment_cases` SET `scenario_text`='" . $db->prepare($OLD) . "' "
            . "WHERE `dimension_group`='love_language' AND `dimension`='words' "
            . "AND `scenario_text`='" . $db->prepare($NEW) . "'"
        );
    },
);
